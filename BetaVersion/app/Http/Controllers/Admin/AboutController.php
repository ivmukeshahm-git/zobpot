     * Update the specified resource in storage.
     *
     * @param  \Illuminate\Http\Request  $request
     * @param  int  $id
     * @return \Illuminate\Http\Response
     */
    public function update(Request $request, $id)
    {
        // Validation rules - adjust fields as needed
        $validator = Validator::make($request->all(), [
            'description'       => 'required',
        ]);

        if ($validator->fails()) {
            return response()->json([
                'status' => 0,
                'message' => $validator->errors()->first()
            ], 200);
        }

        try {
            // Update the setting record by ID
            DB::table('tbl_setting')
                ->where('id', $id)
                ->update([
                    'about_us'  => $request->input('description'),
                ]);

            StaffActivityController::insertActivity(Auth::user()->id, 'Website About Us updated successfully.');


            return response()->json([
                'status'  => 1,
                'message' => 'About updated successfully.'
            ]);
        } catch (\Exception $e) {
            return response()->json([
                'status'  => 0,
                'message' => 'Failed to update settings.',
                'error'   => $e->getMessage() // remove in production
            ]);
        }
    }

